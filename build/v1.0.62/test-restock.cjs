'use strict';
const assert=require('node:assert/strict');
const a=require('./nano-restock-assistant.js');
const day=new Date(2026,9,15);
assert.equal(a.days('2026-10-15',day),0);
assert.equal(a.days('2026-10-22',day),7);
assert.equal(a.days('2026-10-14',day),-1);
assert.equal(a.days('2026-02-30',day),null);
assert.equal(a.stock({stock:0,quantity:55}),0);
assert.equal(a.stock({batches:[{stock:2},{stock:3}]}),5);
assert.equal(a.fromResponse({items:[{id:1}],total:1}).items.length,1);
assert.equal(a.fromResponse({data:{rows:[{id:2}],total:1}}).total,1);
assert.throws(()=>a.fromResponse({success:false}));
let r=a.classify({name:'Milk',stock:2,min_stock:6,expiry_date:'2026-10-21'},day);
assert.equal(r.low,true);assert.equal(r.reorder,7);assert.equal(r.expiryDays,6);
r=a.classify({stock:0,min_stock:1,batches:[{stock:0,expiry_date:'2024-01-01'}]},day);
assert.equal(r.expired,false);assert.equal(r.low,true);
r=a.classify({stock:10,min_stock:3,expiry_date:'2026-09-01'},day);
assert.equal(r.expired,true);
assert.equal(a.classify({stock:10,min_stock:3,expiry_date:'2027-09-01'},day),null);
const s=a.summarize([{name:'A',stock:1,min_stock:2},{name:'B',stock:5,min_stock:2,expiry_date:'2026-10-12'},{name:'C',stock:5,min_stock:2,expiry_date:'2026-10-25'}],day);
assert.equal(s.low,1);assert.equal(s.expired,1);assert.equal(s.expiring,1);
console.log('PASS read-only stock and expiry calculations');
